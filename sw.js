/* =============================================================================
   Служебный поток (service worker): офлайн и установка «на главный экран».

   Зачем он нужен. Установить .apk может не каждый: где-то заблокированы
   сервисы Google, где-то установщик производителя отказывается ставить
   пакет из неизвестного источника, а на iPhone .apk не поставить в
   принципе. Этот файл делает то же самое без единого магазина: браузер
   предлагает «Установить приложение», ярлык появляется на главном экране,
   а пособие открывается без интернета — как обычная программа.

   Стратегия — «отдать из кэша, следом обновить» (stale-while-revalidate):

     • страница открывается мгновенно и работает без сети;
     • в это же время файл тихо перекачивается, и в кэш ложится свежая
       версия — её увидят при следующем запуске.

   Почему не «сначала сеть»: пособием пользуются на школьном wifi, где сеть
   формально есть, но еле дышит. Ждать ответа сервера ради текста, который
   уже лежит на диске, незачем.

   Почему не «только кэш»: тогда обновление не доехало бы никогда.

   Списка файлов здесь намеренно нет. Он бы устаревал при каждом
   переименовании: в пособии больше сотни файлов симуляций, шрифты KaTeX и
   стили. Вместо списка кэшируется всё, что приложение само запросило при
   первом открытии, — так кэш не может разойтись с содержимым.
   ============================================================================= */
'use strict';

const КЭШ = 'physim';

/* Не ждём, пока закроются все вкладки со старым потоком: пособие открыто в
   одной вкладке, и «обновится когда-нибудь потом» здесь только путает. */
self.addEventListener('install', e => {
  self.skipWaiting();
  // Оболочку кладём сразу: без неё офлайн не открылась бы самая первая
  // страница, если сеть пропала ровно между установкой и первым запросом.
  e.waitUntil(caches.open(КЭШ).then(c => c.addAll(['./', './index.html']).catch(() => {})));
});

self.addEventListener('activate', e => {
  e.waitUntil((async () => {
    // чужие кэши от прошлых версий этого файла
    for (const имя of await caches.keys()) if (имя !== КЭШ) await caches.delete(имя);
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', e => {
  const req = e.request;

  // Чужие домены и всё, кроме обычного получения страницы, не трогаем.
  if (req.method !== 'GET') return;
  if (new URL(req.url).origin !== self.location.origin) return;

  e.respondWith((async () => {
    const кэш = await caches.open(КЭШ);
    const своё = await кэш.match(req);

    const сеть = fetch(req).then(ответ => {
      /* В кэш кладём только удачные ответы. Иначе одна страница ошибки,
         пойманная в метро, осталась бы там навсегда. */
      if (ответ && ответ.ok && ответ.type === 'basic') кэш.put(req, ответ.clone());
      return ответ;
    }).catch(() => null);

    if (своё) return своё;                    // есть на диске — отдаём немедленно

    const ответ = await сеть;
    if (ответ) return ответ;

    /* Сети нет, в кэше пусто. Для перехода по страницам отдаём оболочку:
       у пособия один вход, и открыть его лучше, чем показать ошибку. */
    if (req.mode === 'navigate') {
      const оболочка = await кэш.match('./index.html');
      if (оболочка) return оболочка;
    }
    return Response.error();
  })());
});
