/* Проверка модели ученика (js/learn.js) — без браузера.

   1. Журнал → освоение → статус: решённые задачи поднимают тему, ошибки
      опускают, свежие ошибки дают «трудности».
   2. Граф: фронт — темы, все предпосылки которых освоены; блокеры — то,
      что мешает теме, ближние первыми, освоенное не раскрывается.
   3. Повторение: срок уходит всё дальше после каждого удачного возврата,
      провал на повторении откатывает.
   4. Диагностика: двенадцать задач с конечным ответом; совет начинает с
      провала, у которого нет проваленных предпосылок.
   5. Веер ошибок на всех задачах курса: каждый промах, который модуль умеет
      называть, воспроизводится «испорченными» параметрами и узнаётся;
      верный ответ промахом не называется никогда.
   6. Тренажёры: у каждого навыка упражнения с конечным ответом; перевод
      единиц сверен с вычислителем.
   7. «От вопроса»: каждая строка ведёт в существующую тему и симуляцию,
      которая в этой теме действительно используется.

   Запуск:  npm run learn
*/
import { readFileSync, readdirSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const читать = p => readFileSync(join(ROOT, p), 'utf8');
globalThis.document = { querySelector: () => null };
const ядро = new Function(читать('js/core.js') + ';return {SIMS, идЗадачи};')();
globalThis.SIMS = ядро.SIMS; globalThis.идЗадачи = ядро.идЗадачи;
for (const f of readdirSync(join(ROOT, 'js/sims')).filter(f => f.endsWith('.js')).sort())
  new Function(читать('js/sims/' + f))();
const { ALL } = new Function(читать('js/topics.js') + ';return {ALL};')();
const В = new Function(читать('js/calc.js') + ';return ВЫЧ;')();
const У = new Function(читать('js/learn.js') + ';return УЧ;')();
const SIMS = ядро.SIMS, идЗадачи = ядро.идЗадачи;

const беды = [];
const ok = (имя, усл, инфо) => {
  console.log((усл ? '  ok   ' : '  FAIL ') + имя + (инфо === undefined ? '' : '  ' + JSON.stringify(инфо)));
  if (!усл) беды.push(имя);
};
const тема = id => ALL.find(t => t.id === id);
const ДЕНЬ = У.ДЕНЬ, T0 = Date.UTC(2026, 0, 10);
const умолч = def => { const p = {}; for (const q of def.params || []) if (q.key) p[q.key] = q.default; return p; };
const ед = u => { try { const q = В.считать('1 ' + u); return { k: q.siv, си: В.размерностьТекст(q.d) }; } catch (e) { return null; } };
let зерно = 4242;
const rnd = () => { зерно = (зерно * 16807) % 2147483647; return зерно / 2147483647; };

/* ---------------- 1. освоение ---------------- */
{
  const t = тема('mech.1d');
  let ж = У.новыйЖурнал();
  const реш = (pr, ok, dt = 0) => { ж = У.записатьПопытку(ж, { тема: t.id, задача: идЗадачи(t, pr), уровень: pr.level, ok, t: T0 + dt }); };
  const с0 = У.состояние(ж, ALL, T0);
  ok('пустой журнал: тема не начата, фронт — первые темы курса',
    с0.темы['mech.1d'].статус === 'new' && с0.фронт[0] === 'mech.1d' && !с0.фронт.includes('mech.dyn'), с0.фронт.slice(0, 4));
  реш(t.problems[0], false); реш(t.problems[0], true);
  const с1 = У.состояние(ж, ALL, T0);
  ok('одна решённая задача — «в работе»', с1.темы['mech.1d'].статус === 'work' && с1.темы['mech.1d'].освоение > 0, с1.темы['mech.1d']);
  for (const pr of t.problems.slice(1, 4)) реш(pr, true);
  const с2 = У.состояние(ж, ALL, T0 + 1000);
  ok('четыре задачи — освоена, на фронт выходит двумерное движение',
    с2.темы['mech.1d'].статус === 'done' && с2.фронт.includes('mech.2d') && !с2.фронт.includes('mech.1d'), { т: с2.темы['mech.1d'], фронт: с2.фронт.slice(0, 3) });
  let ж2 = У.новыйЖурнал();
  const t2 = тема('mech.dyn');
  for (let k = 0; k < 4; k++) ж2 = У.записатьПопытку(ж2, { тема: t2.id, задача: идЗадачи(t2, t2.problems[k % 2]), уровень: 2, ok: false, t: T0 + k });
  const с3 = У.состояние(ж2, ALL, T0 + 10);
  ok('четыре свежих промаха — «трудности»', с3.темы['mech.dyn'].статус === 'stuck' && с3.трудности.includes('mech.dyn'), с3.темы['mech.dyn']);
  const бл = У.блокеры(с3, ALL, 'mech.dyn');
  ok('блокеры «Динамики»: 1D и 2D, ближние первыми', бл.map(b => b.id).join() === 'mech.1d,mech.2d', бл);
  // с освоенной 1D она из блокеров уходит и дальше не раскрывается
  const бл2 = У.блокеры(У.состояние(ж, ALL, T0 + 1000), ALL, 'mech.grav').map(b => b.id);
  ok('освоенная предпосылка не блокирует', !бл2.includes('mech.1d') && бл2.includes('mech.dyn'), бл2);
  // вопросы самопроверки двигают освоение
  let ж3 = У.новыйЖурнал();
  (тема('mech.osc').checks || []).forEach((_, i) => { ж3 = У.записатьВопрос(ж3, 'mech.osc', i, true, T0); });
  ok('«знал» в самопроверке засчитывается', У.состояние(ж3, ALL, T0).темы['mech.osc'].освоение > 0);
  ok('битый журнал чинится, а не роняет', У.состояние(У.починить({ задачи: 5 }), ALL, T0).фронт.length > 0);
}

/* ---------------- 2. повторение ---------------- */
{
  const t = тема('mech.1d');
  let ж = У.новыйЖурнал();
  const раз = (k, ok, day) => { ж = У.записатьПопытку(ж, { тема: t.id, задача: идЗадачи(t, t.problems[k]), уровень: t.problems[k].level, ok, t: T0 + day * ДЕНЬ }); };
  for (let k = 0; k < 4; k++) раз(k, true, 0);
  const сроки = [ж.темы['mech.1d'].след];
  const ст = d => У.состояние(ж, ALL, T0 + d * ДЕНЬ).темы['mech.1d'].статус;
  const до = ст(1), в = ст(3);
  раз(0, true, 3); сроки.push(ж.темы['mech.1d'].след);
  раз(1, true, 3 + 6); сроки.push(ж.темы['mech.1d'].след);
  const шаги = сроки.map((s, i) => i ? Math.round((s - сроки[i - 1]) / ДЕНЬ) : 0);
  ok('срок повторения: освоена → «пора повторить» → интервал растёт',
    до === 'done' && в === 'due' && шаги[1] > 0 && (сроки[2] - T0 - 9 * ДЕНЬ) > (сроки[1] - T0 - 3 * ДЕНЬ), { до, в, шаги });
  const этап = ж.темы['mech.1d'].этап;
  раз(2, false, 60);
  ok('провал на повторении откатывает этап и возвращает через день',
    ж.темы['mech.1d'].этап === этап - 1 && Math.round((ж.темы['mech.1d'].след - T0) / ДЕНЬ) === 61, ж.темы['mech.1d']);
}

/* ---------------- 3. диагностика ---------------- */
{
  const набор = У.выбратьДиагностику(ALL, SIMS, rnd);
  const плохо = набор.filter(({ тема: id, i }) => {
    const pr = тема(id).problems[i];
    let v; try { v = pr.answer(умолч(SIMS[pr.sim])); } catch (e) { return true; }
    return !isFinite(v);
  });
  ok(`диагностика: ${набор.length} тем, у каждой задача с симуляцией`, набор.length === 12 && набор.every(x => тема(x.тема).problems[x.i].sim), набор.map(x => x.тема));
  ok('ответ при умолчаниях конечен (или подберётся перебором)', плохо.length <= 3, плохо);
  const с = У.советДиагностики({ 'mech.1d': 'ok', 'mech.2d': 'ok', 'mech.dyn': 'fail', 'mech.energy': 'fail', 'mech.osc': 'skip', 'el.current': 'fail' }, ALL);
  ok('совет: начать с «Динамики» — у неё нет проваленных предпосылок', с.начать === 'mech.dyn' && с.потом.includes('mech.energy'), с);
  ok('совет без провалов — пуст', У.советДиагностики({ 'mech.1d': 'ok' }, ALL).начать === null);
}

/* ---------------- 4. веер ошибок ---------------- */
{
  let задач = 0, сПромахом = 0, узнано = 0, ложных = 0, верныхПромахом = 0;
  const виды = {}, провал = [];
  for (const t of ALL) for (const pr of t.problems || []) {
    if (!pr.sim || !SIMS[pr.sim]) continue;
    задач++;
    const def = SIMS[pr.sim], p = умолч(def);
    let верно; try { верно = pr.answer(p); } catch (e) { continue; }
    if (!isFinite(верно)) continue;
    if (У.веерОшибок(pr, p, def, верно, ед).length) верныхПромахом++;
    // воспроизводим каждый промах из параметров и проверяем, что он узнаётся
    const полей = {}; for (const q of def.params) if (q.key) полей[q.key] = q;
    const пробы = [];
    for (const k in p) {
      const q = полей[k]; if (!q) continue;
      if (q.unit === '°' && typeof p[k] === 'number' && p[k] !== 45) пробы.push(['sin-cos', { [k]: 90 - p[k] }]);
      if (typeof p[k] === 'boolean') пробы.push(['модель', { [k]: !p[k] }]);
      if (typeof p[k] === 'number' && q.unit && !/°/.test(q.unit) && q.type !== 'select') {
        const e = ед(q.unit); if (e && Math.abs(e.k - 1) > 1e-9) пробы.push(['единицы', { [k]: p[k] / e.k }]);
      }
    }
    const числ = Object.keys(p).filter(k => полей[k] && typeof p[k] === 'number' && полей[k].unit && полей[k].unit !== '°' && полей[k].type !== 'select');
    for (let a = 0; a < числ.length; a++) for (let b = a + 1; b < числ.length; b++)
      if (полей[числ[a]].unit === полей[числ[b]].unit && p[числ[a]] !== p[числ[b]]) пробы.push(['перепутаны', { [числ[a]]: p[числ[b]], [числ[b]]: p[числ[a]] }]);
    let был = false;
    for (const [вид, изм] of пробы) {
      let v; try { v = pr.answer(Object.assign({}, p, изм)); } catch (e) { continue; }
      if (!isFinite(v) || У.близко(v, верно)) continue;
      // тот же ответ может дать и другой, более простой промах (знак, ×2) —
      // тогда веер вправе назвать его; засчитываем узнавание любого из них
      const другие = У.веерОшибок(pr, p, def, v, ед);
      if (другие.length && !другие.some(x => x.вид === вид) && другие[0].вид !== вид && ['знак', 'множитель', 'порядок', 'g', 'степень'].includes(другие[0].вид)) { узнано++; был = true; continue; }
      был = true;
      const в = У.веерОшибок(pr, p, def, v, ед);
      if (в.some(x => x.вид === вид)) { узнано++; виды[вид] = (виды[вид] || 0) + 1; }
      else провал.push(`${t.id}/${pr.sim}: ${вид} → ${JSON.stringify(в)}`);
    }
    if (был) сПромахом++;
    // случайное число далеко от всех промахов не должно получать объяснений
    const чужое = верно * (1.37 + 0.11 * (задач % 5));
    if (У.веерОшибок(pr, p, def, чужое, ед).length) ложных++;
  }
  ok(`верный ответ никогда не называется промахом (${задач} задач)`, верныхПромахом === 0, верныхПромахом);
  ok(`промахи из параметров узнаются: ${узнано} случаев в ${сПромахом} задачах`, провал.length === 0 && узнано > 100, провал.slice(0, 5));
  ok('случайное число редко получает объяснение (< 10 %)', ложных < задач * 0.1, { ложных, задач });
  // перевод единиц: сантиметры, подставленные как метры
  const t = тема('mech.osc'), pr = t.problems.find(x => x.sim === 'pendulum');
  const def = SIMS.pendulum;
  const ключСм = def.params.find(q => q.unit === 'см' || q.unit === 'г');
  const знак = У.веерОшибок(pr, умолч(def), def, -pr.answer(умолч(def)), ед);
  ok('потерянный знак и приставка узнаются по самому числу',
    знак.some(x => x.вид === 'знак') && У.веерОшибок(pr, умолч(def), def, pr.answer(умолч(def)) * 1000, ед).some(x => x.вид === 'порядок'), знак);
  // явный случай единиц: задача, читающая параметр в сантиметрах
  let единицы = null;
  for (const tt of ALL) for (const p2 of tt.problems || []) {
    if (единицы || !p2.sim || !SIMS[p2.sim]) continue;
    const d2 = SIMS[p2.sim], пар = умолч(d2);
    for (const q of d2.params) {
      if (!q.key || typeof пар[q.key] !== 'number' || !q.unit || /°/.test(q.unit)) continue;
      const e = ед(q.unit); if (!e || Math.abs(e.k - 1) < 1e-9) continue;
      let v, в; try { в = p2.answer(пар); v = p2.answer(Object.assign({}, пар, { [q.key]: пар[q.key] / e.k })); } catch (_) { continue; }
      if (!isFinite(v) || У.близко(v, в)) continue;
      const r = У.веерОшибок(p2, пар, d2, v, ед);
      единицы = { задача: tt.id + '/' + p2.sim, поле: q.label, единица: q.unit, узнано: r.some(x => x.вид === 'единицы'), r };
      break;
    }
  }
  ok('непереведённая единица узнаётся', единицы && единицы.узнано, единицы);
  void ключСм;
}

/* ---------------- 5. тренажёры ---------------- */
{
  const плохо = [];
  let упражнений = 0;
  for (const [id, н] of Object.entries(У.НАВЫКИ)) {
    if (!н.имя || !н.суть || !н.правило) плохо.push(id + ': нет текста');
    if (!н.упр) continue;
    for (let k = 0; k < 40; k++) {
      const u = н.упр(rnd, В); упражнений++;
      if (!u.вопрос || !isFinite(u.ответ)) { плохо.push(id + ': ' + JSON.stringify(u)); break; }
    }
  }
  ok(`тренажёры: ${упражнений} упражнений, у всех конечный ответ`, плохо.length === 0, плохо);
  const пер = [['72 км/ч', 'м/с', 20], ['45 см', 'м', 0.45], ['2,7 г/см³', 'кг/м³', 2700], ['13,6 эВ', 'Дж', 13.6 * 1.602176634e-19]];
  const сверка = пер.filter(([из, в, ждём]) => Math.abs(В.считать(из).siv / В.считать('1 ' + в).siv - ждём) > Math.abs(ждём) * 1e-9);
  ok('перевод единиц в тренажёре идёт через вычислитель', сверка.length === 0, сверка);
  const приёмы = new Function(читать('js/ops.js') + ';return ПРИЁМЫ;')();
  const безПриёма = Object.entries(У.НАВЫКИ).filter(([, н]) => !приёмы[н.приём]).map(([id, н]) => id + '→' + н.приём);
  ok('у каждого навыка есть статья в справочнике приёмов', безПриёма.length === 0, безПриёма);
  let ж = У.новыйЖурнал();
  for (let k = 0; k < 5; k++) ж = У.записатьТренажёр(ж, 'знак', true, T0 + k);
  ж = У.записатьПопытку(ж, { тема: 'mech.1d', задача: 'x', ok: false, навык: 'знак', t: T0 - 10 });
  ж = У.записатьПопытку(ж, { тема: 'mech.1d', задача: 'x', ok: false, навык: 'единицы', t: T0 });
  const рем = У.навыкиКРемонту(ж, T0 + 100).map(x => x.навык);
  ok('пять верных подряд чинят навык: старые ошибки уходят из ремонта', !рем.includes('знак') && рем.includes('единицы'), рем);
}

/* ---------------- 6. от вопроса ---------------- */
{
  const плохо = [];
  for (const в of У.ВОПРОСЫ) {
    const t = тема(в.тема);
    if (!t) { плохо.push('нет темы ' + в.тема); continue; }
    if (!SIMS[в.sim]) { плохо.push('нет симуляции ' + в.sim); continue; }
    if (!JSON.stringify(t).includes("'" + в.sim + "'") && !JSON.stringify(t).includes('"' + в.sim + '"')) плохо.push(`${в.sim} не встречается в теме ${в.тема}`);
  }
  const разделов = new Set(У.ВОПРОСЫ.map(в => в.раздел)).size;
  ok(`«от вопроса»: ${У.ВОПРОСЫ.length} вопросов в ${разделов} разделах ведут в живые темы и симуляции`, плохо.length === 0 && У.ВОПРОСЫ.length >= 36, плохо);
}

console.log(беды.length ? `\nмодель ученика: провалов ${беды.length}` : '\nмодель ученика сходится');
process.exit(беды.length ? 1 : 0);
