/* Проверка вычислителя (js/calc.js) — без браузера.

   1. Счёт с единицами: переводы, производные единицы, приставки, ошибки
      размерности с понятным текстом.
   2. Погрешность: сверка с формулой распространения и с корреляцией —
      (x ± 1) − x обязано давать 0 ± 0, а два независимых измерения — √2.
   3. Формулы курса: сколько разбирается, и что формулы с производными
      не разбираются (d·x/(d·t) «сократилось» бы в x/t).
   4. Сквозная сверка решателя: каждую разобранную формулу решаем
      относительно каждой её величины при случайных значениях остальных,
      подставляем ответ обратно — равенство обязано выполниться. Это
      проверяет и выражение неизвестного, и численный поиск корней.

   Запуск:  npm run calc
*/
import { readFileSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const читать = p => readFileSync(join(ROOT, p), 'utf8');
const В = new Function(читать('js/calc.js') + ';return ВЫЧ;')();
globalThis.document = { querySelector: () => null };
const { ALL } = new Function(читать('js/core.js') + читать('js/topics.js') + '; return {ALL};')();

const беды = [];
const ok = (имя, усл, инфо) => {
  console.log((усл ? '  ok   ' : '  FAIL ') + имя + (инфо === undefined ? '' : '  ' + JSON.stringify(инфо)));
  if (!усл) беды.push(имя);
};
const счёт = s => { try { return В.считать(s); } catch (e) { return { ошибка: e.message }; } };

/* ---------------- 1. единицы ---------------- */
{
  const случаи = [
    ['72 км/ч в м/с', '20 м/с'],
    ['0,5 · 2 кг · (3 м/с)²', '9 Дж'],
    ['9,8 м/с² · 2 с', '19,6 м/с'],
    ['1 кДж в Дж', '1000 Дж'],
    ['101 325 Па в атм', '1 атм'],
    ['h c / (500 нм) в эВ', '2,48 эВ'],
    ['m_e c^2 в МэВ', '0,511 МэВ'],
    ['kB · 300 К в эВ', '0,02585 эВ'],
    ['sin(30°)', '0,5'],
    ['1500 об/мин в рад/с', '157,1 рад/с'],
    ['√(2 g · 10 м)', '14 м/с'],
    ['NA kB', '8,314 Дж/(моль·К)'],
    ['5 мкФ', '5·10⁻⁶ Ф'],
  ];
  const плохо = случаи.map(([s, ждём]) => [s, счёт(s).текст || счёт(s).ошибка, ждём]).filter(([, был, ждём]) => был !== ждём);
  ok('единицы, переводы и постоянные', плохо.length === 0, плохо);

  const ошибки = [
    ['2 м + 3 с', /одинаковое/],
    ['ln(5 м)', /безразмерного/],
    ['2 м в с', /разная размерность/],
    ['2 м2', /м²/],
    ['log(2)', /ln .* lg/],
    ['x', /неизвестное обозначение/],
  ];
  const нет = ошибки.map(([s, re]) => [s, счёт(s).ошибка || 'без ошибки']).filter(([s, e], k) => !ошибки[k][1].test(e));
  ok('ошибки размерности названы по-человечески', нет.length === 0, нет);

  const р1 = счёт('Н = кг·м/с²'), р2 = счёт('Дж = Н');
  ok('проверка размерности равенства', р1.сходится === true && р2.сходится === false && /м/.test(р2.разница), { р1: р1.текст, р2: р2.текст });
  const s = счёт('sin 30');
  ok('sin без градусов предупреждает о радианах', s.заметки && s.заметки.some(z => /радиан/.test(z)), s.заметки);
}

/* ---------------- 2. погрешность ---------------- */
{
  const a = счёт('(2,5 ± 0,1) м / (3,0 ± 0,2) с');
  const σ = (2.5 / 3) * Math.sqrt(Math.pow(0.1 / 2.5, 2) + Math.pow(0.2 / 3, 2));
  ok('деление: σ по формуле распространения', Math.abs(a.σ - σ) < 1e-12 && a.текст === '0,83 ± 0,06 м/с', { σ: a.σ, ждём: σ, текст: a.текст });
  const b = счёт('3 кг ± 2 %');
  ok('относительная погрешность и значащие нули', b.текст === '3,00 ± 0,06 кг', b.текст);
  const c = счёт('(10 ± 1) м − (10 ± 1) м');
  ok('два независимых измерения: погрешность √2', Math.abs(c.σ - Math.SQRT2) < 1e-12, c.σ);
  // одна и та же величина дважды — через переменную: коррелированы
  const env = В.окружение();
  const x = В.величина('10 ± 1 м', env);
  env.пер = { x };
  const d = В.оформить(В.вычислитьУзел(В.разобрать('x - x'), env), env);
  ok('одна величина минус она же: 0 ± 0', d.σ === 0 && d.v === 0, d.текст);
  const e = счёт('((2,0 ± 0,1) м) ^ 2');
  ok('степень: σ(x²) = 2x·σ', Math.abs(e.σ - 0.4) < 1e-12, e.текст);
}

/* ---------------- 3. формулы курса ---------------- */
let формул = 0, разобрано = 0;
const равенства = [];
{
  const производные = [];
  for (const t of ALL) for (const f of t.formulas || []) {
    формул++;
    try {
      const eqs = В.изTeX(f.tex); разобрано++;
      for (const eq of eqs) равенства.push({ тема: t.id, tex: f.tex, eq });
      // d·x/(d·t) в разобранном — значит производная прошла как произведение
      for (const eq of eqs) if (/\\dfrac\{d [^{}]*\}\{d /.test(В.вTeX(eq))) производные.push(f.tex);
    } catch (e) { /* нерешаемая — это нормально */ }
  }
  ok(`формулы курса разбираются: ${разобрано} из ${формул}`, разобрано >= 180, { разобрано, формул });
  ok('формулы с производными не выдаются за произведение', производные.length === 0, производные.slice(0, 3));
}

/* ---------------- 4. сквозная сверка решателя ---------------- */
{
  let случаев = 0, выражено = 0, численно = 0, нетРешения = 0;
  const провал = [];
  let зерно = 12345;
  const случ = () => { зерно = (зерно * 16807) % 2147483647; return зерно / 2147483647; };
  for (const { тема, eq } of равенства) {
    const пер = В.переменные(eq);
    for (const x of пер) {
      случаев++;
      const вводы = {};
      for (const п of пер) if (п !== x) вводы[п] = String(+(0.2 + 0.6 * случ()).toFixed(4));
      let р;
      try { р = В.решить(eq, x, вводы); }
      catch (e) { if (/нет решения|за пределы|отрицательного|больше 1|деление на ноль/.test(e.message)) { нетРешения++; continue; } провал.push(`${тема} ${x}: ${e.message}`); continue; }
      if (р.способ === 'выражено') выражено++; else численно++;
      // подставляем обратно
      const env = В.окружение();
      const знач = {};
      for (const п of пер) знач[п] = п === x ? { v: р.ответ.siv, d: р.ответ.d, g: {} } : В.величина(вводы[п], env);
      env.пер = знач;
      const лев = В.вычислитьУзел(eq.a, env).v, прав = В.вычислитьУзел(eq.b, env).v;
      // значения порядка единицы: «0 = 10⁻¹⁷» — равенство, а не невязка
      const разн = Math.abs(лев - прав) / Math.max(Math.abs(лев), Math.abs(прав), 1e-9);
      if (!(разн < 1e-6)) провал.push(`${тема} ${x}: ${В.вTeX(eq)} → ${р.ответ.текст}, невязка ${разн.toExponential(1)}`);
    }
  }
  ok(`решатель: ответ удовлетворяет формуле (${случаев} случаев: выражено ${выражено}, численно ${численно}, без решения ${нетРешения})`,
    провал.length === 0 && нетРешения < случаев * 0.1, провал.slice(0, 6));
}

/* ---------------- 5. размерность неизвестного ---------------- */
{
  const [eq] = В.изTeX('T=2\\pi\\sqrt{\\dfrac{L}{g}}');
  const T = В.решить(eq, 'T', { L: '1 м', g: '9,8 м/с²' });
  const g = В.решить(eq, 'g', { T: '(2,00 ± 0,01) с', L: '(1,000 ± 0,005) м' });
  ok('маятник: период в секундах, g с погрешностью в м/с²',
    T.ответ.текст === '2,007 с' && g.ответ.текст === '9,87 ± 0,11 м/с²' && g.способ === 'выражено' &&
    g.tex === 'g=\\dfrac{4 \\pi^{2} L}{T^{2}}', { T: T.ответ.текст, g: g.ответ.текст, tex: g.tex });
  const [путь] = В.изTeX('x=x_0+v_0t+\\tfrac12at^2');
  const t = В.решить(путь, 't', { x: '10 м', 'x_{0}': '0 м', 'v_{0}': '0 м/с', a: '9,8 м/с²' });
  ok('время падения с 10 м находится численно и в секундах', t.способ === 'численно' && t.ответ.текст === '1,429 с', t.ответ.текст);
  let ошибка = '';
  try { В.решить(путь, 't', { x: '10 м', 'x_{0}': '0 м', 'v_{0}': '0 м/с', a: '9,8 м/с' }); } catch (e) { ошибка = e.message; }
  ok('несогласованные единицы в формуле — ошибка размерности', /размерност/.test(ошибка), ошибка);
}

/* ---------------- 6. ответы задач с единицами ---------------- */
{
  // каждая единица задач курса должна разбираться, кроме логарифмических
  const единицы = new Set();
  for (const t of ALL) for (const pr of t.problems || []) единицы.add(pr.unit || '');
  const не = [...единицы].filter(u => u !== 'дБ' && В.ответЗадачи('1 ' + (u.replace(/^×\s*/, '') || ''), u).ошибка);
  ok(`единицы ответов всех ${единицы.size} видов разбираются (кроме дБ)`, не.length === 0, не);
  const а = В.ответЗадачи('2,5 мДж', 'мкДж'), б = В.ответЗадачи('3 Н', 'Дж'), в = В.ответЗадачи('42', 'м/с'),
    г = В.ответЗадачи('30°', '°'), д = В.ответЗадачи('400 км', '×10³ км'), е = В.ответЗадачи('25 %', '%');
  ok('ответ с единицами переводится в единицы задачи',
    Math.abs(а.u - 2500) < 1e-9 && в.u === 42 && Math.abs(г.u - 30) < 1e-9 && Math.abs(д.u - 0.4) < 1e-12 && Math.abs(е.u - 25) < 1e-9,
    { а: а.u, в: в.u, г: г.u, д: д.u, е: е.u });
  ok('не та размерность в ответе названа и объяснена',
    б.размерность && б.надо === 'Дж' && б.есть === 'Н' && /не хватает множителя «м»/.test(б.подсказка), б);
}

console.log(беды.length ? `\nвычислитель: провалов ${беды.length}` : '\nвычислитель сходится');
process.exit(беды.length ? 1 : 0);
