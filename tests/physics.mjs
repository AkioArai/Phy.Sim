/* Сверка симуляций с аналитическими решениями.
   =============================================
   Каждая проверка задаёт параметры, прогоняет симуляцию и сравнивает её
   ПОКАЗАНИЯ с числом, посчитанным здесь по формуле из учебника. Показания
   для этого и годятся: они подписаны физическими величинами, и брать их
   надёжнее, чем лазить во внутреннее состояние каждой из 76 моделей.

   Правила, которых держится этот файл:

   • параметры берутся НЕ умолчаниями. На умолчаниях легко получить
     случайное совпадение (например ноль или единицу), а неверный
     коэффициент проявится только на «некруглых» числах;
   • эталон считается из независимой формулы, а не из кода симуляции —
     иначе проверялось бы, что код равен самому себе;
   • у численного интегрирования есть своя погрешность, поэтому у каждой
     проверки указан допуск, и он обоснован: величины, которые симуляция
     считает алгебраически, сверяются с 1e-9, а результат интегрирования
     движения — с 1e-3…1e-2.

   Запуск:  npm i -D playwright && npm run physics
*/
