/* Помощники для extra: пишутся строкой, поэтому живут отдельно и вставляются
   в текст функции подстановкой. */
const EX = {
  // радиус окружности по крайним точкам траектории (по обеим осям — заодно
  // видно, что это окружность, а не эллипс)
  radius: `const xs=hist.map(h=>h.x), ys=hist.map(h=>h.y);
    const rx=(Math.max(...xs)-Math.min(...xs))/2, ry=(Math.max(...ys)-Math.min(...ys))/2;
    out.push(['траектория: радиус по x',rx],['траектория: радиус по y',ry]);`,
  // разброс модуля скорости за прогон: 0 означает строгое сохранение
  speedSpread: `const sp=hist.map(h=>Math.hypot(h.vx,h.vy));
    out.push(['скорость: разброс за прогон',(Math.max(...sp)-Math.min(...sp))/Math.max(...sp)]);`,
  // среднее по времени от намагниченности на последних 80 % прогона:
  // мгновенное значение у конечного числа доменов шумит, среднее — нет
  avgM: `const h2=hist.slice(Math.floor(hist.length*0.2));
    out.push(['M: среднее по прогону',h2.reduce((a,h)=>a+h.M,0)/h2.length]);`,
  // отношение показаний: нужно там, где ожидаемое значение — ноль, и «ноль»
  // осмысленен только по сравнению с масштабом задачи
  ratio: (label, base, name) => `{const g=l=>{const r=ro.find(q=>String(q[0]).startsWith(l)); return r?r[1]:NaN;};
    out.push([${JSON.stringify(name)}, g(${JSON.stringify(label)})/Math.abs(g(${JSON.stringify(base)}))]);}`,

  /* ЗАКОНЫ СОХРАНЕНИЯ. Здесь проверяется не формула, а поведение за весь
     прогон: сохраняющаяся величина не должна ни расти, ни убывать. Нужен
     traceRO — показания записываются на каждом кадре.
       drift  — наибольшее относительное отклонение от начального значения;
       growth — наибольший РОСТ (для величин, которым разрешено только убывать:
                механическая энергия при трении, кинетическая при ударах). */
  drift: (label, name, scale) => `{const pick=l=>histRO.map(m=>{
      const k=Object.keys(m).find(q=>q.startsWith(l)); return m[k]; }).filter(Number.isFinite);
    const v=pick(${JSON.stringify(label)});
    const sc=${scale ? `Math.max(...pick(${JSON.stringify(scale)}).map(Math.abs))` : 'Math.max(...v.map(Math.abs))'}||1;
    out.push([${JSON.stringify(name)}, Math.max(...v.map(x=>Math.abs(x-v[0])))/sc]);}`,
  growth: (label, name) => `{const v=histRO.map(m=>{
      const k=Object.keys(m).find(q=>q.startsWith(${JSON.stringify(label)})); return m[k]; }).filter(Number.isFinite);
    const sc=Math.max(...v.map(Math.abs))||1;
    let g=0; for(const x of v) g=Math.max(g,(x-v[0])/sc);
    out.push([${JSON.stringify(name)}, g]);}`,
};

