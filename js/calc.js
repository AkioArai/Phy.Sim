        if (c === 'mathrm' && рм) { const f = { k: 'fn', f: рм }; f.a = аргументФункции(); return f; }
        if (c === 'text' && единица(t)) return { k: 'unit', w: t };
        if (c === 'text' && t === 'const') return { k: 'const' };
        if (c === 'text' && единицыСтрокой(t)) return { k: 'units', w: t };
        if (c === 'text') нельзя('слово «' + t + '»');
