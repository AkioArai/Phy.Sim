  function подобратьЕдиницу(d) {
    if (dБезр(d)) return { текст: '', f: 1, простая: false };
    for (const [имя, dd] of ПРОИЗВОДНЫЕ) if (dРавны(d, dd)) return { текст: имя, f: 1, простая: !!ПРИСТАВЛЯЕМЫЕ[имя] };
    // из основных: кг·м²/(с³·А)
    const числ = [], знам = [];
    d.forEach((p, i) => {
      if (Math.abs(p) < 1e-9) return;
      const r = Math.round(p * 1000) / 1000;
      const t = ОСНОВА[i] + (Math.abs(r) === 1 ? '' : СТЕПЕНИ(Math.abs(r)));
      (r > 0 ? числ : знам).push(t);
    });
    // чтобы кг шёл первым, как принято
    const порядок = x => x.indexOf('кг') === 0 ? 0 : x.indexOf('м') === 0 ? 1 : 2;
    числ.sort((a, b) => порядок(a) - порядок(b));
    let текст = числ.length ? числ.join('·') : '1';
    if (знам.length) текст += '/' + (знам.length > 1 ? '(' + знам.join('·') + ')' : знам[0]);
    const простая = числ.length === 1 && !знам.length && ПРИСТАВЛЯЕМЫЕ[числ[0]];
    return { текст, f: 1, простая: !!простая };
  }

  /* ---------------- запись числа ---------------- */
  function степеньДесяти(n) { return '10' + СТЕПЕНИ(n); }
  function число(v, знаков) {
    if (v === 0) return '0';
    if (!isFinite(v)) return v > 0 ? '∞' : '−∞';
    const a = Math.abs(v);
    if (a >= 1e5 || a < 1e-3) {
      const e = Math.floor(Math.log10(a));
      let m = v / Math.pow(10, e);
      let t = m.toPrecision(знаков || 4);
      if (Math.abs(parseFloat(t)) >= 10) { m /= 10; t = m.toPrecision(знаков || 4); return чистить(t) + '·' + степеньДесяти(e + 1); }
      return чистить(t) + '·' + степеньДесяти(e);
    }
    return чистить(v.toPrecision(знаков || 4));
  }
  function чистить(t) {
    if (t.indexOf('e') >= 0) t = String(parseFloat(t));
    if (t.indexOf('.') >= 0) t = t.replace(/0+$/, '').replace(/\.$/, '');
    return t.replace('-', '−').replace('.', ',');
  }
  /* Значение ± погрешность по правилам записи результата измерения:
     погрешность — одна значащая цифра (две, если первая 1 или 2), значение
     округлено до того же разряда. Общий множитель 10ⁿ выносится за скобку. */
  function сПогрешностью(v, σ) {
    if (!(σ > 0)) return { текст: число(v), σтекст: '' };
    const разрσ = Math.floor(Math.log10(σ));
    const перв = Math.floor(σ / Math.pow(10, разрσ));
    const цифр = перв <= 2 ? 2 : 1;
    const шаг = разрσ - (цифр - 1);                 // разряд последней значащей цифры
    const общ = Math.abs(v) >= 1e5 || (Math.abs(v) < 1e-3 && Math.abs(v) > 0) || σ >= 1e5 || σ < 1e-3
      ? Math.floor(Math.log10(Math.max(Math.abs(v), σ))) : 0;
    const окр = x => Math.round(x / Math.pow(10, шаг)) * Math.pow(10, шаг);
    const знаков = Math.max(0, общ - шаг);
    // нули в конце здесь значащие: 3,00 ± 0,06, а не 3 ± 0,06
    const фмт = x => (окр(x) / Math.pow(10, общ)).toFixed(знаков).replace('-', '−').replace('.', ',');
    const t = фмт(v) + ' ± ' + фмт(σ);
    return { текст: общ ? '(' + t + ')·' + степеньДесяти(общ) : t, σтекст: фмт(σ) };
  }

  const ПРИСТ_ВЫВОД = [[1e9, 'Г'], [1e6, 'М'], [1e3, 'к'], [1, ''], [1e-3, 'м'], [1e-6, 'мк'], [1e-9, 'н'], [1e-12, 'п']];

  /* Итог: текст ответа, погрешность, запасная запись с приставкой. */
  function оформить(q, env, цель) {
    const σ = сигма(q, env.σ);
    let единицаТекст, f;
    if (цель) { единицаТекст = цель.текст; f = цель.f; }
    else { const e = подобратьЕдиницу(q.d); единицаТекст = e.текст; f = 1; }
    const v = q.v / f, s = σ / f;
    const гл = сПогрешностью(v, s);
    const итог = {
      v, σ: s, единица: единицаТекст, текст: гл.текст + (единицаТекст ? ' ' + единицаТекст : ''),
      относительная: s > 0 && v !== 0 ? Math.abs(s / v) : 0, d: q.d, siv: q.v, siσ: σ,
      заметки: env.заметки.slice(), понято: env.понято.map(n => ({ имя: n, что: ПОСТ[n].что, v: ПОСТ[n].v, d: ПОСТ[n].d })),
    };
    // та же величина с приставкой: 3,2·10⁻⁶ Ф = 3,2 мкФ
    if (!цель) {
      const e = подобратьЕдиницу(q.d);
      if (e.простая && v !== 0) {
        const a = Math.abs(v);
        const н = ПРИСТ_ВЫВОД.find(([k]) => a >= k * 0.99995 && a / k < 999.95);
        if (н && н[0] !== 1) итог.иначе = сПогрешностью(v / н[0], s / н[0]).текст + ' ' + н[1] + e.текст;
      }
    }
    if (q.угол) итог.иначе = сПогрешностью(q.v * 180 / ПИ, σ * 180 / ПИ).текст + '°';
    return итог;
  }

  /* ---------------- вход «как есть»: строка → ответ ---------------- */
  function считать(строка, переменные) {
    const дерево = разобрать(строка);
    const env = окружение(переменные);
    if (дерево.k === 'eq') return сравнить(дерево, env);
    if (дерево.k === 'conv') {
      const q = вычислитьУзел(дерево.a, env);
      const env2 = окружение();
      const ц = вычислитьУзел(дерево.to, env2);
      if (Object.keys(ц.g).length) throw Ошибка('в единице перевода не может быть погрешности', 0);
      if (!dРавны(q.d, ц.d))
        throw Ошибка('перевести ' + (размерностьТекст(q.d) || 'число') + ' в ' + (размерностьТекст(ц.d) || 'число') +
          ' нельзя: у них разная размерность', 0);
      return Object.assign(оформить(q, env, { текст: дерево.текст, f: ц.v }), { вид: 'число' });
    }
    return Object.assign(оформить(вычислитьУзел(дерево, env), env), { вид: 'число' });
  }

  /* «Н = кг·м/с²» — проверка размерности. Если стоят числа, сверяются и они. */
  function сравнить(дерево, env) {
    const a = вычислитьУзел(дерево.a, env), b = вычислитьУзел(дерево.b, env);
    const сходится = dРавны(a.d, b.d);
    const res = { вид: 'равенство', сходится, слева: размерностьТекст(a.d), справа: размерностьТекст(b.d), заметки: env.заметки.slice() };
    if (!сходится) {
      const разн = dВыч(a.d, b.d);
      res.разница = размерностьТекст(разн);
      res.текст = 'Размерности не сходятся: слева ' + (res.слева) + ', справа ' + (res.справа) +
        '. Левая часть больше правой в «' + res.разница + '».';
    } else {
      const числаРавны = Math.abs(a.v - b.v) <= 1e-9 * Math.max(Math.abs(a.v), Math.abs(b.v), 1e-300);
      res.числаРавны = числаРавны;
      res.текст = 'Размерности сходятся: обе части — ' + (res.слева === 'безразмерная' ? 'безразмерные' : res.слева) + '.' +
        (числаРавны ? '' : ' Числа при этом разные: ' + число(a.v) + ' и ' + число(b.v) + '.');
    }
    return res;
  }

