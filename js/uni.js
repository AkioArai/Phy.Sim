function естьВуз(t){ return !!(t&&ВУЗ[t.id]&&ВУЗ[t.id].length); }
function уровеньВуз(){ return typeof prefGet==='function'&&prefGet('level')==='uni'; }
function вузHTML(t){
  if(!естьВуз(t)||!уровеньВуз()) return '';
  return `<section class="uni"><h2 class="sect">Вузовский уровень</h2>${ВУЗ[t.id].map(b=>
    `<div class="uni-b"><h3>${b.h}</h3>${b.html}</div>`).join('')}</section>`;
}
/* Переключатель в шапке темы: виден только у тем, где есть вузовский раздел. */
function переключательУровня(t){
  const ch=document.querySelector('#content .chead'); if(!ch) return;
  let el=document.getElementById('t-lvl');
  if(!el){ el=document.createElement('div'); el.id='t-lvl'; el.className='t-lvl'; el.setAttribute('role','group'); el.setAttribute('aria-label','Уровень изложения');
    el.innerHTML='<button data-l="school">Школа</button><button data-l="uni">Вуз</button>';
    const sub=document.getElementById('t-sub'); if(sub) sub.after(el); else ch.appendChild(el);
    el.querySelectorAll('button').forEach(b=>b.onclick=()=>{
      if(!S.settings) S.settings={};
      try{ prefSet('level',b.dataset.l); }catch(_){ S.settings.level=b.dataset.l; }
      переключательУровня(S.topic); renderPane();
      if(b.dataset.l==='uni'){ const u=document.querySelector('#pane .uni'); if(u) try{ u.scrollIntoView({block:'start',behavior:'smooth'}); }catch(_){} }
    }); }
  el.classList.toggle('hidden',!естьВуз(t));
  const ур=уровеньВуз()?'uni':'school';
  el.querySelectorAll('button').forEach(b=>b.classList.toggle('on',b.dataset.l===ур));
}
