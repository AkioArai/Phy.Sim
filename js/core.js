/* ===================== НОМЕР ЗАДАЧИ =====================
   Отметка «решено» раньше хранилась по ПОРЯДКОВОМУ номеру задачи внутри темы
   («mech.1d#3»). Порядок — не имя: стоило вставить задачу в середину темы, и
   у всех, кто уже решал, галочки съезжали на соседние условия. Ошибка тихая:
   приложение уверенно показывает решённой задачу, которую никто не решал.

   Имя задачи теперь выводится из её условия. Условие и есть то, что отличает
   одну задачу от другой: переставили — номер тот же, вставили соседнюю —
   чужие номера не тронуты. Плата за это одна: правка формулировки меняет
   номер и сбрасывает отметку по этой задаче. Поэтому у задачи можно объявить
   `id` явно — тогда текст правится свободно. Расхождения показывает
   `npm run curriculum` по слепку docs/problem-ids.json. */
function хэшСтроки(s){
  let h=0x811c9dc5;                                   // FNV-1a, 32 бита
  s=String(s);
  for(let i=0;i<s.length;i++){ h^=s.charCodeAt(i); h=Math.imul(h,0x01000193)>>>0; }
  return h.toString(36);
}
